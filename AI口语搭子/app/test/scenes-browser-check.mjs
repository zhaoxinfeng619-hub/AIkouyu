import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { APP_ROOT } from '../server/config.mjs';
import { fixture } from './fixtures.mjs';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
const missing = await fixture(null, { missing: ['DASHSCOPE_API_KEY', 'DASHSCOPE_WORKSPACE_ID'] });
const configured = await fixture(null);
const output = path.join(APP_ROOT, '.local/verification');
fs.mkdirSync(output, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], sessions = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if(req.method() === 'POST' && req.url().endsWith('/api/sessions')) sessions.push(req.postDataJSON()); });
  await page.goto(missing.base);
  await page.waitForFunction(() => document.querySelectorAll('.scene-card').length === 6);
  await page.locator('#scene-grid img').evaluateAll(images => Promise.all(images.map(img => img.decode())));
  assert.equal(sessions.length, 0);
  assert.equal(await page.locator('.scene-tag').filter({ hasText: '练习过' }).count(), 0);
  await page.screenshot({ path: path.join(output, 'scenes-home-desktop.png'), fullPage: true });
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({ path: path.join(output, 'scenes-home-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('.scene-favorite').first().click();
  await page.locator('#favorites-filter').click();
  assert.equal(await page.locator('.scene-card').count(), 1);
  await page.reload();
  await page.locator('#favorites-filter').click();
  assert.equal(await page.locator('.scene-card').count(), 1, 'Favorite survives reload');
  await page.locator('.scene-favorite').click();
  assert.equal(await page.locator('#empty-favorites').isVisible(), true);
  await page.locator('#show-all-scenes').click();
  await page.locator('[data-category="travel"]').click();
  assert.equal(await page.locator('.scene-card').count(), 2);
  await page.locator('[data-category="all"]').click();
  await page.locator('[data-scene="coffee"]').click();
  assert.equal(await page.locator('#detail-title').innerText(), '咖啡店点单');
  assert.equal(await page.locator('#character-profile-title').innerText(), '认识 Alex');
  assert.match(await page.locator('#character-meta').innerText(), /男 · 25 岁 · 咖啡师/);
  assert.match(await page.locator('#character-voice').innerText(), /男声/);
  assert.equal(await page.locator('#detail-tasks li').count(), 3);
  await page.screenshot({ path: path.join(output, 'scenes-detail-mobile.png'), fullPage: true });
  await page.locator('#detail-enter').click();
  assert.equal(await page.locator('#start-button').isDisabled(), true);
  await page.screenshot({ path: path.join(output, 'scenes-call-mobile.png'), fullPage: true });
  await page.locator('#orb-preview-button').click();
  await page.waitForFunction(() => document.querySelector('#orb-preview-status').textContent.includes('动效预览'));
  await page.locator('.call-mode-picker [data-mode="orb"]').click();
  await page.waitForTimeout(300);
  await page.screenshot({ path: path.join(output, 'scenes-orb-mobile.png'), fullPage: true });
  assert.equal(sessions.length, 0, 'Browsing and both visual modes never create a paid session');
  assert.equal(await page.locator('#transcript .utterance').count(), 0);
  await page.locator('#call-back').click();
  assert.equal(await page.locator('#orb-preview-button').getAttribute('aria-pressed'), 'false');
  await page.goto(configured.base);
  await page.locator('[data-scene="hotel"]').click();
  await page.locator('#detail-enter').click();
  await page.waitForFunction(() => !document.querySelector('#start-button').disabled);
  await page.locator('#start-button').click();
  await page.waitForFunction(() => document.querySelector('#state-label').textContent === '正在聆听');
  assert.equal(sessions.at(-1).scene, 'hotel');
  const connectionCount = configured.connections.length;
  const provider = configured.connections.at(-1);
  assert.equal((await provider.inbox.wait('session.update')).session.audio.output.voice, 'Mione');
  await provider.inbox.wait('input_audio_buffer.append');
  await page.locator('.call-mode-picker [data-mode="orb"]').click();
  await page.locator('.call-mode-picker [data-mode="scene"]').click();
  assert.equal(configured.connections.length, connectionCount);
  assert.equal(sessions.length, 1, 'Modes share one ongoing voice session');
  provider.send({ type: 'conversation.item.input_audio_transcription.completed', item_id: 'scene-user', transcript: 'I have a reservation.' });
  await page.waitForFunction(() => document.querySelector('#caption-text').textContent === 'I have a reservation.');
  provider.send({ type: 'response.audio_transcript.done', response_id: 'scene-reply', item_id: 'scene-assistant', transcript: 'Welcome! I am Olivia.' });
  await page.waitForFunction(() => document.querySelector('#caption-text').textContent === 'Welcome! I am Olivia.');
  assert.equal(await page.locator('#transcript-title').innerText(), '与 Olivia 的对话');
  assert.equal(await page.locator('#transcript .assistant .speaker').innerText(), 'Olivia');
  await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.copiedText = text; } } }); });
  await page.locator('#copy-button').click();
  assert.match(await page.evaluate(() => window.copiedText), /Olivia：Welcome/);
  assert.doesNotMatch(await page.evaluate(() => window.copiedText), /口语搭子：/);
  await page.locator('#call-back').click();
  await page.waitForFunction(() => document.body.dataset.view === 'detail');
  assert.equal(await page.locator('#state-label').innerText(), '本次已结束');
  assert.equal(await page.locator('#transcript .assistant .speaker').innerText(), 'Olivia');
  await page.locator('#detail-back').click();
  assert.equal(await page.locator('[data-scene="hotel"] .scene-tag').innerText(), '✓ 练习过');
  await page.locator('[data-scene="coffee"]').click();
  await page.locator('#detail-enter').click();
  assert.equal(await page.locator('#transcript-title').innerText(), '与 Alex 的对话');
  assert.equal(await page.locator('#transcript .utterance').count(), 0, 'Changing character clears previous transcript');
  assert.deepEqual(errors, []);
  console.log('Scene UI passed: six real assets, category/favorites, detail tasks, mobile layout, zero-session previews, selected role reaches API, live mode switch keeps one session, subtitles, exit stops call, practiced only after speech. No cloud calls.');
} finally { await browser.close(); await missing.close(); await configured.close(); }
